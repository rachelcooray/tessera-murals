/**
 * Moderation helpers: perceptual hashing for near-duplicates, a submission rate limit,
 * and a scan of an upload's embedded metadata for signs it was made with an AI image tool.
 * None of these decide on their own. They raise flags for the person reviewing.
 */

/**
 * Difference hash ("dHash") of an image already reduced to 9 × 8 greyscale values (72 numbers, row by row).
 * Returns 16 hex characters (64 bits).
 */
export function dHash(grey9x8: ArrayLike<number>): string {
  if (grey9x8.length !== 72) throw new Error("dHash needs a 9 × 8 greyscale image");
  let bits = "";
  for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x++) bits += grey9x8[y * 9 + x] < grey9x8[y * 9 + x + 1] ? "1" : "0";
  let hex = "";
  for (let i = 0; i < 64; i += 4) hex += parseInt(bits.slice(i, i + 4), 2).toString(16);
  return hex;
}

/** Greyscale 9 × 8 from RGBA pixels of any size, by box averaging. */
export function greyThumb(data: ArrayLike<number>, width: number, height: number): number[] {
  const out: number[] = [];
  for (let gy = 0; gy < 8; gy++) for (let gx = 0; gx < 9; gx++) {
    const x0 = Math.floor((gx * width) / 9), x1 = Math.max(x0 + 1, Math.floor(((gx + 1) * width) / 9));
    const y0 = Math.floor((gy * height) / 8), y1 = Math.max(y0 + 1, Math.floor(((gy + 1) * height) / 8));
    let sum = 0, n = 0;
    for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) {
      const i = (y * width + x) * 4;
      sum += 0.299 * data[i] + 0.587 * data[i + 1] + 0.114 * data[i + 2]; n++;
    }
    out.push(n ? sum / n : 0);
  }
  return out;
}

/** Number of differing bits between two 16-character hex hashes. */
export function hamming(a: string, b: string): number {
  let d = 0;
  for (let i = 0; i < 16; i++) {
    let x = parseInt(a[i] ?? "0", 16) ^ parseInt(b[i] ?? "0", 16);
    while (x) { d += x & 1; x >>= 1; }
  }
  return d;
}

/** The closest earlier hash within the limit, or null. */
export function findNearDuplicate(hash: string, earlier: { id: string; hash: string }[], maxDistance: number): { id: string; distance: number } | null {
  let best: { id: string; distance: number } | null = null;
  for (const e of earlier) {
    const d = hamming(hash, e.hash);
    if (d <= maxDistance && (!best || d < best.distance)) best = { id: e.id, distance: d };
  }
  return best;
}

/** True when another submission now would go over the hourly limit. */
export function overRateLimit(timestamps: number[], now: number, perHour: number): boolean {
  const since = now - 3600_000;
  return timestamps.filter((t) => t > since).length >= perHour;
}

/**
 * Text markers that AI image tools write into files: the IPTC "digital source type" for
 * generated media (used in C2PA Content Credentials and XMP), and common generator names.
 */
const AI_MARKERS: [RegExp, string][] = [
  [/trainedAlgorithmicMedia/i, "Content Credentials say it was generated by AI"],
  [/compositeWithTrainedAlgorithmicMedia/i, "Content Credentials say it was edited with generative AI"],
  [/Midjourney/i, "Metadata mentions Midjourney"],
  [/DALL[·.\- ]?E/i, "Metadata mentions DALL·E"],
  [/Stable ?Diffusion|ComfyUI|AUTOMATIC1111|sd-webui/i, "Metadata mentions Stable Diffusion"],
  [/Adobe Firefly|Generative Fill/i, "Metadata mentions Adobe Firefly"],
  [/Imagen|Gemini|ImageFX/i, "Metadata mentions a Google image model"],
  [/ChatGPT|OpenAI/i, "Metadata mentions OpenAI"],
  [/"parameters"|Negative prompt:/i, "File carries image-generation settings"],
];

/** Signs of AI generation in the first part of a file. An empty list means nothing was found, not that it is hand-made. */
export function scanForAiMarkers(bytes: Uint8Array): string[] {
  const head = bytes.subarray(0, Math.min(bytes.length, 256 * 1024));
  let text = "";
  for (let i = 0; i < head.length; i++) {
    const c = head[i];
    text += c >= 32 && c < 127 ? String.fromCharCode(c) : " ";
  }
  const found = new Set<string>();
  for (const [re, label] of AI_MARKERS) if (re.test(text)) found.add(label);
  return [...found];
}

/** True when the file carries Content Credentials (a C2PA manifest) at all. */
export function hasContentCredentials(bytes: Uint8Array): boolean {
  const head = bytes.subarray(0, Math.min(bytes.length, 256 * 1024));
  for (let i = 0; i < head.length - 4; i++) {
    if (head[i] === 0x63 && head[i + 1] === 0x32 && head[i + 2] === 0x70 && head[i + 3] === 0x61) return true; // "c2pa"
  }
  return false;
}
