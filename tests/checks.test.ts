import { test } from "node:test";
import assert from "node:assert/strict";
import { dHash, findNearDuplicate, greyThumb, hamming, hasContentCredentials, overRateLimit, scanForAiMarkers } from "../src/lib/mosaic/checks.ts";
import { bestOpenSlot, colourMatch, colourName, sampleGrid, tintPixels } from "../src/lib/mosaic/colours.ts";

function gradient(w: number, h: number, flip = false): number[] {
  const d: number[] = [];
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) { const v = Math.round(((flip ? w - x : x) / w) * 255); d.push(v, v, v, 255); }
  return d;
}

test("same picture hashes the same, a different one does not", () => {
  const a = dHash(greyThumb(gradient(64, 64), 64, 64));
  const b = dHash(greyThumb(gradient(128, 128), 128, 128));
  const c = dHash(greyThumb(gradient(64, 64, true), 64, 64));
  assert.equal(hamming(a, b), 0);
  assert.ok(hamming(a, c) > 30);
  assert.deepEqual(findNearDuplicate(b, [{ id: "t1", hash: a }], 6), { id: "t1", distance: 0 });
  assert.equal(findNearDuplicate(c, [{ id: "t1", hash: a }], 6), null);
});

test("rate limit counts the last hour only", () => {
  const now = Date.parse("2026-11-01T12:00:00Z");
  const recent = Array.from({ length: 20 }, (_, i) => now - i * 60_000);
  assert.equal(overRateLimit(recent, now, 20), true);
  assert.equal(overRateLimit(recent.map((t) => t - 3600_000), now, 20), false);
});

test("AI metadata markers are found", () => {
  const enc = (s: string) => new TextEncoder().encode(s);
  assert.deepEqual(scanForAiMarkers(enc("…Iptc4xmpExt:DigitalSourceType=http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia…")), ["Content Credentials say it was generated by AI"]);
  assert.ok(scanForAiMarkers(enc("Software: Midjourney v7")).length === 1);
  assert.equal(scanForAiMarkers(enc("Canon EOS R6, f/2.8")).length, 0);
  assert.equal(hasContentCredentials(enc("jumb c2pa manifest")), true);
});

test("grid sampling, naming and best slot", () => {
  // 2 × 1 image: red pixel, blue pixel
  const slots = sampleGrid([200, 30, 30, 255, 30, 30, 200, 255], 2, 1, 2, 1);
  assert.equal(slots.length, 2);
  assert.equal(slots[0].hex, "#c81e1e");
  assert.equal(bestOpenSlot([40, 40, 190], slots, () => true), 1);
  assert.equal(bestOpenSlot([40, 40, 190], slots, (i) => i !== 1), 0);
  assert.equal(bestOpenSlot([40, 40, 190], slots, () => false), -1);
  assert.equal(colourName([222, 159, 108]), "late apricot");
  assert.ok(colourMatch([10, 10, 10], [10, 10, 10]) === 1);
});

test("tint pulls colours toward the slot and keeps light and shade", () => {
  const px = new Uint8ClampedArray([60, 140, 120, 255, 200, 230, 220, 255]);
  const before = colourMatch([px[0], px[1], px[2]], [222, 159, 108]);
  tintPixels(px, "#de9f6c", 0.6);
  assert.ok(colourMatch([px[0], px[1], px[2]], [222, 159, 108]) > before);
  assert.ok(px[4] + px[5] + px[6] > px[0] + px[1] + px[2]); // lighter pixel stays lighter
  const same = new Uint8ClampedArray([1, 2, 3, 255]);
  tintPixels(same, "#ff0000", 0);
  assert.deepEqual([...same], [1, 2, 3, 255]);
});
